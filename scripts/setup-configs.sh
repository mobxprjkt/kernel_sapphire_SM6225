#!/usr/bin/env bash
# Enable only SukiSU-Nova, SUSFS and KPM.
set -euo pipefail
: "${DEFCONFIG:?}"
[ -f "$DEFCONFIG" ] || { echo "[ERROR] Defconfig not found: $DEFCONFIG" >&2; exit 1; }

# Remove any previous KSU/SUSFS/KPM entries so this script is idempotent.
sed -i \
  -e '/^CONFIG_KSU=/d' \
  -e '/^CONFIG_KPM=/d' \
  -e '/^CONFIG_KALLSYMS=/d' \
  -e '/^CONFIG_KALLSYMS_ALL=/d' \
  -e '/^CONFIG_KSU_SUSFS/d' \
  -e '/^CONFIG_NTSYNC=/d' \
  -e '/^# CONFIG_NTSYNC /d' \
  -e '/^# CONFIG_KSU_SUSFS/d' \
  "$DEFCONFIG"

cat >> "$DEFCONFIG" <<'EOF'

# SukiSU-Nova + SUSFS + KPM only
# CONFIG_NTSYNC is not set
CONFIG_KSU=y
CONFIG_KPM=y
CONFIG_KALLSYMS=y
CONFIG_KALLSYMS_ALL=y
CONFIG_KSU_SUSFS=y
CONFIG_KSU_SUSFS_SUS_MAP=y
CONFIG_KSU_SUSFS_SUS_PATH=y
CONFIG_KSU_SUSFS_SUS_MOUNT=y
CONFIG_KSU_SUSFS_SUS_KSTAT=y
CONFIG_KSU_SUSFS_SPOOF_UNAME=y
# CONFIG_KSU_SUSFS_SUS_OVERLAYFS is not set
CONFIG_KSU_SUSFS_AUTO_ADD_SUS_KSU_DEFAULT_MOUNT=y
CONFIG_KSU_SUSFS_AUTO_ADD_SUS_BIND_MOUNT=y
CONFIG_KSU_SUSFS_TRY_UMOUNT=y
CONFIG_KSU_SUSFS_AUTO_ADD_TRY_UMOUNT_FOR_BIND_MOUNT=y
CONFIG_KSU_SUSFS_ENABLE_LOG=y
CONFIG_KSU_SUSFS_HIDE_KSU_SUSFS_SYMBOLS=y
CONFIG_KSU_SUSFS_SPOOF_CMDLINE_OR_BOOTCONFIG=y
CONFIG_KSU_SUSFS_OPEN_REDIRECT=y
CONFIG_KSU_SUSFS_SUS_SU=y
EOF

echo "[CHECK] KPM config requested"
grep -qx 'CONFIG_KPM=y' "$DEFCONFIG"
grep -qx 'CONFIG_KALLSYMS=y' "$DEFCONFIG"
grep -qx 'CONFIG_KALLSYMS_ALL=y' "$DEFCONFIG"
echo "[OK] Enabled SukiSU-Nova + SUSFS + KPM + required kallsyms"
